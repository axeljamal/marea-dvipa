"""Write ORIGINS.md, LOCK.md, colourways.json, hash every file into manifest.lock.json, copy the verifier."""
import json, hashlib, os, glob, shutil
from draw import COLOURWAYS, MOTIFS
PKG = "pkg/dua-pulau-signature"
ORI = json.load(open("origins.json")); SRC = json.load(open("sources.json"))
md = ["# Dua Pulau — Origins & Recognition", "",
      "*Dua pulau* means \"two islands\". This signature collection is our own original work, drawn from scratch. It grows out of two living traditions, and we name them every time we use it.", "",
      "## Where it comes from", "",
      "**Bomba, Central Sulawesi.** *Bomba* is the Kaili word for flower. The bomba flower is an old motif of the Donggala *buya bomba*, a hand-woven ikat sarong of the Kaili people, traditionally gold on black, worn at weddings, rites and in royal dress. Batik Bomba grew in Palu from 2008, when local makers learned batik with teachers from Pekalongan and began stamping bomba, clove, souraja and maleo designs. *Batik Bomba* is also a registered trademark of a Palu business (2015). Our collection is **Bomba-inspired** and not affiliated with any maker or brand.", "",
      "**Bali.** The navy, teal and gold palette, the pearl keylines and the companion motifs come from the Balinese master edition (barong, candi bentar, lotus) built earlier in this project.", "",
      "**Batik craft.** Isen-isen, the dotted and lined fills drawn with the canting, belong to the wider Indonesian batik tradition recognised by UNESCO in 2009.", "",
      "**Mathematics.** Petal rings, ray counts and dot rings follow Fibonacci numbers and the golden angle. This is our own articulation and is not part of the source traditions.", "",
      "## Motif by motif", "",
      "| Motif | Inspired by | What we made our own | Meaning we honour |", "|---|---|---|---|"]
for slug in list(MOTIFS) + ["rebung-ribbon", "isen-cecek", "isen-zigzag", "isen-sero"]:
    o = ORI[slug]
    md.append(f"| {slug} | {o['inspired_by']} | {o['made_our_own']} | {o['meaning_honoured']} |")
md += ["", "## How to credit it", "", "Wherever these motifs are published, printed or sold, include a line such as:", "",
       "> Dua Pulau signature: original designs inspired by the Bomba flower of the Kaili people (Donggala and Palu, Central Sulawesi) and by Balinese ornament, with gratitude to the weavers and batik makers who keep these traditions alive.", "",
       "## Care", "",
       "- Ceremonial objects (taiganja pendant, sambulugana betel set) are deliberately left out of everyday prints.",
       "- Meanings above are taken from the cited studies and local reporting. Some historical claims in those sources (for example dates for the Banawa kingdom) are not well verified, so we present them as tradition, not fact.",
       "", "## Sources", ""]
for k, s in SRC.items():
    md.append(f"- [{s['title']}]({s['url']})")
open(PKG + "/ORIGINS.md", "w").write("\n".join(md) + "\n")
open(PKG + "/LOCK.md", "w").write("""# Dua Pulau Signature v1.1.0 (LOCKED)

This is an original collection, generated by `_source/draw.py`. Every motif has a fixed seed, so running `python3 draw.py` rebuilds the exact same SVGs.
It uses the same production template as the Bali editions. Each motif folder holds:
- SVG masters in two colourways
- transparent PNGs at 2048 and 512 px
- a preview
- `spec.json`, which also records origins and sources

`07-rebung-ribbon/` holds the continuous rebung: `source/rebung.js` draws it along any path (straight, diagonal, wave, spiral, arcs). Locked samples come in both colourways. It is the same code Batik Pattern Studio runs.\n\n`isen-isen/` holds the three seamless fill tiles (cecek, zigzag and sero) in both colourways, with repeat swatches.

## Colourways
- **dua-pulau:** navy, teal, gold and pearl, meeting the Bali master palette.
- **buya-bomba:** gold on black, after the two-colour Donggala cloth.

Read ORIGINS.md before publishing anything from this collection. Run `python3 verify_lock.py` to check nothing has drifted.
""")
json.dump(COLOURWAYS, open(PKG + "/colourways.json", "w"), indent=2)
sha = lambda p: hashlib.sha256(open(p, "rb").read()).hexdigest()
man = {"collection": "Dua Pulau signature", "version": "1.1.0", "status": "LOCKED", "colourways": COLOURWAYS, "assets": []}
for d in sorted(glob.glob(PKG + "/[0-9][0-9]-*")):
    sp = json.load(open(d + "/spec.json"))
    sp["files"] = {os.path.relpath(f, d): {"sha256": sha(f), "bytes": os.path.getsize(f)} for f in sorted(glob.glob(d + "/**/*", recursive=True)) if os.path.isfile(f) and not f.endswith("spec.json")}
    json.dump(sp, open(d + "/spec.json", "w"), indent=2)
    man["assets"].append({"id": sp["id"], "folder": os.path.basename(d), "files": {k: v["sha256"] for k, v in sp["files"].items()}, "spec_sha256": sha(d + "/spec.json")})
for extra in ["isen-isen", "_source"]:
    fs = sorted(glob.glob(f"{PKG}/{extra}/*"))
    man["assets"].append({"id": extra, "folder": extra, "files": {os.path.basename(f): sha(f) for f in fs}})
man["origins_sha256"] = sha(PKG + "/ORIGINS.md")
json.dump(man, open(PKG + "/manifest.lock.json", "w"), indent=2)
shutil.copy("/home/claude/m2/pkg/bali-batik-motifs-master/verify_lock.py", PKG + "/verify_lock.py")
print("finalized")
