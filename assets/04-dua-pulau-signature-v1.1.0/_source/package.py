import json, hashlib, os, shutil, glob, datetime, subprocess
from draw import COLOURWAYS, MOTIFS, ISEN
PKG="pkg/dua-pulau-signature"; V="1.1.0"
shutil.rmtree("pkg",ignore_errors=True); os.makedirs(PKG+"/_source"); os.makedirs(PKG+"/isen-isen")
meta=json.load(open("out/meta.json")); ORI=json.load(open("origins.json")); SRC=json.load(open("sources.json"))
now=datetime.datetime.now(datetime.UTC).replace(microsecond=0).isoformat().replace("+00:00","Z")
shutil.copy("draw.py",PKG+"/_source/draw.py")
for i,slug in enumerate(MOTIFS,1):
    d=f"{PKG}/{i:02d}-{slug}"; os.makedirs(d)
    for cw in COLOURWAYS: shutil.copy(f"out/{slug}--{cw}.svg",f"{d}/{slug}--{cw}.svg")
    m=meta[slug]; o=ORI[slug]
    json.dump({"id":slug,"title":m["title"],"collection":"Dua Pulau signature","version":V,"status":"LOCKED","locked_at":now,
      "authorship":"Original drawing, generated by _source/draw.py from a fixed seed (not traced from any existing artwork).",
      "seed":m["seed"],"master":{"viewBox":[0,0,m["w"],m["h"]],"files":{cw:f"{slug}--{cw}.svg" for cw in COLOURWAYS}},
      "origins":{"inspired_by":o["inspired_by"],"made_our_own":o["made_our_own"],"meaning_honoured":o["meaning_honoured"],
                 "sources":[SRC[s] for s in o["sources"]]},
      "colourways":{cw:COLOURWAYS[cw] for cw in COLOURWAYS},
      "reproduction_rules":["Credit the origins (see ORIGINS.md) wherever the motif is published or sold.",
        "Scale proportionally; never stretch.","Recolour only by mapping whole tokens, as a new colourway and version.",
        "Regenerate from draw.py with the same seed rather than editing the SVG.","Run verify_lock.py before release."],
      "files":{}},open(d+"/spec.json","w"),indent=2)
for slug in ISEN:
    for cw in COLOURWAYS: shutil.copy(f"out/{slug}--{cw}.svg",f"{PKG}/isen-isen/{slug}--{cw}.svg")
R=f"{PKG}/07-rebung-ribbon"; os.makedirs(R+"/source")
for f in glob.glob("ribbon/rebung-ribbon-*.svg"): shutil.copy(f,R)
shutil.copy("ribbon/rebung.js",R+"/source/rebung.js"); shutil.copy("ribbon/make_samples.js",R+"/source/make_samples.js")
o=ORI["rebung-ribbon"]
json.dump({"id":"rebung-ribbon","title":"Rebung Ribbon","collection":"Dua Pulau signature","version":V,"status":"LOCKED","locked_at":now,
  "authorship":"Original procedural motif: source/rebung.js draws it along any path; source/make_samples.js renders the locked samples. Same code runs in Batik Pattern Studio.",
  "kind":"path-following ribbon (not a fixed image)",
  "api":{"rebungRibbon(points, halfHeight, colourway, phase)":"returns shapes {d, fill, stroke, sw} or {dot, r, fill} for one polyline of [x, y] points",
         "rebungToSvg(svgElement, shapes)":"draws the shapes into an SVG element (browser)",
         "rebungToCanvas(ctx2d, shapes)":"draws the shapes onto a canvas",
         "polyFromPath(svgPathD, step)":"samples any SVG path string into polylines (browser)"},
  "geometry":{"shoot_spacing":"1.25 x half-height","rows":"two, offset by half a step, pointing to the spine","edge_band":"0.16 x half-height","skip_rule":"no shoots where the curve turns more than 0.75 rad within one shoot width"},
  "samples":sorted(os.path.basename(f) for f in glob.glob("ribbon/rebung-ribbon-*.svg")),
  "origins":{"inspired_by":o["inspired_by"],"made_our_own":o["made_our_own"],"meaning_honoured":o["meaning_honoured"],"sources":[SRC[s] for s in o["sources"]]},
  "colourways":{cw:COLOURWAYS[cw] for cw in COLOURWAYS},
  "reproduction_rules":["Credit the origins (see ORIGINS.md) wherever it is published or sold.","Change the look only in rebung.js, as a new version; never hand-edit the sample SVGs.","Keep half-height at least 8 px on screen and 3 mm in print so the chevrons stay legible.","Use the straight 03-rebung-border image for fixed print borders; use the ribbon for flows, curves and diagonals."],
  "files":{}},open(R+"/spec.json","w"),indent=2)
print("copied")
